<?php

declare(strict_types=1);

/**
 * F2a: verify a published stable or beta GitHub release asset before any installer work.
 * No installed CMS-code/database writes, archive extraction, or admin endpoint.
 * A temporary private download is always discarded after inspection.
 *
 * This is a publisher-controlled source/integrity check, NOT a signed release,
 * coordinated backup, restore proof, or permission to run an update.
 */
final class UpdateOfficialReleasePackage
{
    public const MAX_RELEASE_BYTES = 262144;
    public const MAX_ARCHIVE_BYTES = UpdatePackageReview::MAX_ARCHIVE_BYTES;
    private const REPOSITORY = 'joachimlindhadberg/boilerplate';
    private const ASSET_API = 'https://api.github.com/repos/' . self::REPOSITORY . '/releases/assets/';

    private string $root;
    /** @var Closure|null */
    private ?Closure $metadataTransport;
    /** @var Closure|null */
    private ?Closure $binaryTransport;

    /** Inject transports ONLY from isolated tests, never from HTTP/user inputs. */
    public function __construct(?string $root = null, ?callable $metadataTransport = null, ?callable $binaryTransport = null)
    {
        $original = $root ?? dirname(__DIR__, 2);
        $resolved = realpath($original);
        if (!is_string($resolved) || !is_dir($resolved) || is_link($original)) {
            throw new RuntimeException('Unsafe CMS source root.');
        }
        $this->root = rtrim($resolved, '/');
        $this->metadataTransport = $metadataTransport === null ? null : Closure::fromCallable($metadataTransport);
        $this->binaryTransport = $binaryTransport === null ? null : Closure::fromCallable($binaryTransport);
    }

    /**
     * Returns only sanitized review metadata: no ZIP remains on disk.
     * @return array{status:string,version:string,sha256:string,files:int,install_ready:bool}
     */
    public function reviewLatest(string $channel = 'stable'): array
    {
        return $this->checkLatest(false, $channel);
    }

    /**
     * Prepare a verified, immutable-by-name asset for a later installer.
     * Does NOT extract, apply, migrate or authorize an update.
     * @return array{status:string,version:string,sha256:string,files:int,install_ready:bool}
     */
    public function prepareLatest(string $channel = 'stable'): array
    {
        return $this->checkLatest(true, $channel);
    }

    private function checkLatest(bool $prepare, string $channel): array
    {
        $result = ['status' => 'blocked', 'version' => '', 'sha256' => '', 'files' => 0, 'install_ready' => false];
        $channel = UpdateReleaseVersion::channel($channel);
        $current = $this->installedVersion();
        if ($current === null) return $result;

        try {
            $response = $this->metadataTransport !== null
                ? ($this->metadataTransport)(UpdateReleaseVersion::api(self::REPOSITORY, $channel))
                : self::fetchMetadata(UpdateReleaseVersion::api(self::REPOSITORY, $channel));
        } catch (Throwable $e) {
            $result['status'] = 'network_error';
            return $result;
        }
        if (!is_array($response) || !isset($response['status'], $response['body'])
            || !is_int($response['status']) || !is_string($response['body'])
            || strlen($response['body']) > self::MAX_RELEASE_BYTES) return $result;
        if ($response['status'] === 404) {
            $result['status'] = 'no_release';
            return $result;
        }
        if ($response['status'] !== 200) {
            $result['status'] = 'network_error';
            return $result;
        }
        try {
            $release = json_decode($response['body'], true, 24, JSON_THROW_ON_ERROR);
        } catch (JsonException $e) {
            return $result;
        }
        if (!is_array($release) || ($channel === 'beta' && !array_is_list($release))) return $result;
        $selected = UpdateReleaseVersion::select($release, $channel);
        if ($selected === null) {
            $result['status'] = $channel === 'beta' ? 'no_release' : 'blocked';
            return $result;
        }
        $release = $selected;
        $version = $selected['_bp_version'];
        $result['version'] = $version;
        if (version_compare($version, $current, '<=')) {
            $result['status'] = 'no_new_version';
            return $result;
        }
        if (!is_array($release['assets'] ?? null)) return $result;

        // Stable distribution assets must be deliberately uploaded to the
        // official release; source ZIPs automatically generated by GitHub do NOT qualify.
        $expectedName = 'Boilerplate-CMS-v' . $version . '.zip';
        $matching = [];
        foreach ($release['assets'] as $asset) {
            if (is_array($asset) && ($asset['name'] ?? null) === $expectedName) {
                $matching[] = $asset;
            }
        }
        if (count($matching) !== 1) {
            $result['status'] = 'missing_verified_asset';
            return $result;
        }
        $asset = $matching[0];
        if (!is_int($asset['id'] ?? null) || $asset['id'] < 1
            || ($asset['state'] ?? null) !== 'uploaded'
            || !is_int($asset['size'] ?? null) || $asset['size'] < 1
            || $asset['size'] > self::MAX_ARCHIVE_BYTES
            || !is_string($asset['digest'] ?? null)
            || !preg_match('/^sha256:([a-fA-F0-9]{64})$/D', $asset['digest'], $digestMatch)) {
            $result['status'] = 'invalid_asset_metadata';
            return $result;
        }
        $digest = strtolower($digestMatch[1]);

        $file = null;
        try {
            $vault = $this->privateVault();
            $file = tempnam($vault, '.github-release-');
            if (!is_string($file) || is_link($file) || !is_file($file)) {
                throw new RuntimeException('Cannot create temporary release file.');
            }
            @chmod($file, 0600);
            if ((fileperms($file) & 0077) !== 0) {
                throw new RuntimeException('Unprotected temporary release file.');
            }
            $next = self::ASSET_API . $asset['id'];
            $downloaded = false;
            for ($hop = 0; $hop < 3; $hop++) {
                if ($hop > 0 && !self::isSafeAssetRedirect($next)) {
                    throw new RuntimeException('Untrusted download destination.');
                }
                $http = $this->binaryTransport !== null
                    ? ($this->binaryTransport)($next, $file, self::MAX_ARCHIVE_BYTES)
                    : self::fetchBinary($next, $file);
                if (!is_array($http) || !is_int($http['status'] ?? null)) {
                    throw new RuntimeException('Invalid download transport result.');
                }
                if ($http['status'] === 200) {
                    $downloaded = true;
                    break;
                }
                if (!in_array($http['status'], [301, 302, 303, 307, 308], true)
                    || !is_string($http['location'] ?? null)) {
                    throw new RuntimeException('Release asset cannot be downloaded.');
                }
                $next = $http['location'];
            }
            if (!$downloaded || !is_file($file) || is_link($file)
                || filesize($file) !== $asset['size'] || filesize($file) > self::MAX_ARCHIVE_BYTES) {
                throw new RuntimeException('Download size or destination mismatch.');
            }
            $actual = hash_file('sha256', $file);
            if (!is_string($actual) || !hash_equals($digest, strtolower($actual))) {
                $result['status'] = 'digest_mismatch';
                return $result;
            }
            if (!class_exists('ZipArchive')) {
                $result['status'] = 'zip_extension_required';
                return $result;
            }
            $inspection = (new UpdatePackageReview($this->root))->inspect($file, $asset['size']);
            if (($inspection['status'] ?? null) === 'blocked'
                || ($inspection['target_version'] ?? null) !== $version
                || ($inspection['sha256'] ?? null) !== $actual) {
                $result['status'] = 'invalid_release_package';
                return $result;
            }
            $result['sha256'] = $actual;
            $result['files'] = $inspection['files'];
            if ($prepare) {
                // The file is a *candidate*, never permission to install it.
                $this->persistPreparedAsset($file, $version, $actual, $asset['size'], $inspection['files'], $channel);
                $result['status'] = 'prepared_for_review_only';
            } else {
                $result['status'] = 'verified_for_review_only';
            }
            return $result;
        } catch (Throwable $e) {
            $result['status'] = 'download_or_review_failed';
            return $result;
        } finally {
            if (is_string($file) && is_file($file) && !is_link($file)) @unlink($file);
        }
    }

    /**
     * Read the last prepared artifact without network access or mutating any files.
     * A later installer MUST independently revalidate this package and prove a
     * consistent recovery point; this method is never an install authorization.
     * @return array{status:string,version:string,sha256:string,files:int,install_ready:bool}
     */
    public function preparedStatus(string $channel = 'stable'): array
    {
        $channel = UpdateReleaseVersion::channel($channel);
        $blocked = ['status' => 'not_prepared', 'version' => '', 'sha256' => '', 'files' => 0, 'install_ready' => false];
        $vault = $this->root . '/storage/update-recovery';
        $manifest = $vault . '/.official-stage.json';
        if (!is_dir($vault) || is_link($vault) || (fileperms($vault) & 0077) !== 0
            || is_link($manifest) || !is_file($manifest)
            || filesize($manifest) < 1 || filesize($manifest) > 4096
            || (fileperms($manifest) & 0077) !== 0) return $blocked;
        $encoded = @file_get_contents($manifest);
        if (!is_string($encoded)) return $blocked;
        try { $record = json_decode($encoded, true, 8, JSON_THROW_ON_ERROR); }
        catch (JsonException $e) { return $blocked; }
        if (!is_array($record) || ($record['schema'] ?? null) !== 1
            || ($record['repository'] ?? null) !== self::REPOSITORY
            || !is_string($record['version'] ?? null)
            || !UpdateReleaseVersion::valid($record['version'])
            || ($record['channel'] ?? 'stable') !== $channel
            || !is_string($record['sha256'] ?? null)
            || !preg_match('/^[a-f0-9]{64}$/D', $record['sha256'])
            || !is_int($record['size'] ?? null) || $record['size'] < 1
            || $record['size'] > self::MAX_ARCHIVE_BYTES
            || !is_int($record['files'] ?? null) || $record['files'] < 1
            || ($record['install_ready'] ?? null) !== false
            || !is_int($record['prepared_at'] ?? null) || $record['prepared_at'] > time() + 60) {
            return $blocked;
        }
        $installed = $this->installedVersion();
        if ($installed === null || version_compare($record['version'], $installed, '<=')) return $blocked;
        $zip = $vault . '/.official-release-' . $record['sha256'] . '.zip';
        if (is_link($zip) || !is_file($zip) || filesize($zip) !== $record['size']
            || (fileperms($zip) & 0077) !== 0) return $blocked;
        $actual = @hash_file('sha256', $zip);
        if (!is_string($actual) || !hash_equals($record['sha256'], $actual)) return $blocked;
        return [
            'status' => 'prepared_for_review_only', 'version' => $record['version'],
            'sha256' => $record['sha256'], 'files' => $record['files'], 'install_ready' => false,
        ];
    }

    /** Only verified bytes and sanitized metadata are placed in the private vault. */
    private function persistPreparedAsset(string $temporary, string $version, string $sha, int $size, int $files, string $channel): void
    {
        $vault = $this->privateVault();
        $lockPath = $vault . '/.official-stage.lock';
        if (is_link($lockPath) || (file_exists($lockPath) && !is_file($lockPath))) {
            throw new RuntimeException('Unsafe release staging lock.');
        }
        $lock = @fopen($lockPath, 'c+b');
        if ($lock === false) throw new RuntimeException('Cannot lock release staging.');
        $metadataTemporary = null;
        try {
            @chmod($lockPath, 0600);
            if ((fileperms($lockPath) & 0077) !== 0 || !flock($lock, LOCK_EX)) {
                throw new RuntimeException('Unable to acquire private staging lock.');
            }
            $target = $vault . '/.official-release-' . $sha . '.zip';
            if (is_link($target) || (file_exists($target) && !is_file($target))) {
                throw new RuntimeException('Unsafe existing staged release.');
            }
            if (file_exists($target)) {
                $existing = @hash_file('sha256', $target);
                if (filesize($target) !== $size || !is_string($existing)
                    || !hash_equals($sha, $existing) || (fileperms($target) & 0077) !== 0) {
                    throw new RuntimeException('Existing release is invalid.');
                }
            } elseif (!@rename($temporary, $target)) {
                throw new RuntimeException('Cannot retain the verified release.');
            }
            @chmod($target, 0600);
            if ((fileperms($target) & 0077) !== 0) {
                throw new RuntimeException('Unprotected staged release.');
            }
            $record = json_encode([
                'schema' => 1, 'repository' => self::REPOSITORY,
                'version' => $version, 'channel' => $channel, 'sha256' => $sha, 'size' => $size,
                'files' => $files, 'prepared_at' => time(), 'install_ready' => false,
            ], JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
            $metadataTemporary = @tempnam($vault, '.official-meta-');
            if (!is_string($metadataTemporary) || is_link($metadataTemporary)) {
                throw new RuntimeException('Cannot create private release metadata.');
            }
            @chmod($metadataTemporary, 0600);
            if (@file_put_contents($metadataTemporary, $record, LOCK_EX) !== strlen($record)) {
                throw new RuntimeException('Cannot record release identity.');
            }
            $manifest = $vault . '/.official-stage.json';
            if (is_link($manifest) || (file_exists($manifest) && !is_file($manifest))) {
                throw new RuntimeException('Unsafe release manifest.');
            }
            if (!@rename($metadataTemporary, $manifest)) {
                throw new RuntimeException('Cannot commit private release identity.');
            }
            $metadataTemporary = null;
        } finally {
            if (is_string($metadataTemporary) && is_file($metadataTemporary) && !is_link($metadataTemporary)) {
                @unlink($metadataTemporary);
            }
            flock($lock, LOCK_UN);
            fclose($lock);
        }
    }

    public static function isSafeAssetRedirect(string $url): bool
    {
        if (strlen($url) > 4096 || preg_match('/[\x00-\x20\x7f\\\\]/', $url)) return false;
        $parts = parse_url($url);
        if (!is_array($parts) || ($parts['scheme'] ?? null) !== 'https'
            || !isset($parts['host'], $parts['path']) || ($parts['path'] === '')
            || isset($parts['port']) || isset($parts['fragment'])
            || isset($parts['user']) || isset($parts['pass'])) return false;
        return in_array(strtolower($parts['host']), [
            'release-assets.githubusercontent.com', 'objects.githubusercontent.com',
        ], true) && str_starts_with($parts['path'], '/');
    }

    private function installedVersion(): ?string
    {
        $file = $this->root . '/public_html/incl/init.php';
        if (is_link($file) || !is_file($file)) return null;
        $source = @file_get_contents($file, false, null, 0, 131072);
        if (!is_string($source)
            || !preg_match(UpdateReleaseVersion::SOURCE_PATTERN, $source, $m)) {
            return null;
        }
        return $m[1];
    }

    private function privateVault(): string
    {
        $storage = $this->root . '/storage';
        $vault = $storage . '/update-recovery';
        foreach ([$storage, $vault] as $dir) {
            if (is_link($dir) || (file_exists($dir) && !is_dir($dir))) {
                throw new RuntimeException('Unsafe recovery storage directory.');
            }
            if (!is_dir($dir) && !@mkdir($dir, 0700)) {
                throw new RuntimeException('Unable to create private storage.');
            }
        }
        @chmod($vault, 0700);
        clearstatcache(true, $vault);
        if ((fileperms($vault) & 0077) !== 0) {
            throw new RuntimeException('Recovery download storage must be owner-only.');
        }
        return $vault;
    }

    /** @return array{status:int,body:string} */
    private static function fetchMetadata(string $url): array
    {
        $response = self::request($url, ['Accept: application/vnd.github+json'], self::MAX_RELEASE_BYTES, null);
        return ['status' => $response['status'], 'body' => $response['body']];
    }

    /** @return array{status:int,location:?string} */
    private static function fetchBinary(string $url, string $destination): array
    {
        $response = self::request($url, ['Accept: application/octet-stream'], self::MAX_ARCHIVE_BYTES, $destination);
        return ['status' => $response['status'], 'location' => $response['location']];
    }

    /**
     * Manually handle redirects; no generic URL or user-provided host can be fetched.
     * The destination may hold only a temporary download owned by this service.
     * @return array{status:int,body:string,location:?string}
     */
    private static function request(string $url, array $headers, int $limit, ?string $destination): array
    {
        $headers[] = 'User-Agent: Boilerplate-CMS-Release-Downloader';
        $location = null;
        $body = '';
        $bytes = 0;
        $output = $destination !== null ? @fopen($destination, 'wb') : null;
        if ($destination !== null && $output === false) throw new RuntimeException('Cannot open private download.');
        try {
            if (function_exists('curl_init')) {
                $ch = curl_init($url);
                if ($ch === false) throw new RuntimeException('Cannot initialize HTTPS request.');
                try {
                    $options = [
                        CURLOPT_HTTPHEADER => $headers,
                        CURLOPT_FOLLOWLOCATION => false,
                        CURLOPT_CONNECTTIMEOUT => 5,
                        CURLOPT_TIMEOUT => 30,
                        CURLOPT_SSL_VERIFYPEER => true,
                        CURLOPT_SSL_VERIFYHOST => 2,
                        CURLOPT_RETURNTRANSFER => false,
                        CURLOPT_HEADERFUNCTION => static function ($curl, string $header) use (&$location): int {
                            if (str_starts_with(strtolower($header), 'location:')) {
                                $location = trim(substr($header, 9));
                            }
                            return strlen($header);
                        },
                        CURLOPT_WRITEFUNCTION => static function ($curl, string $chunk) use (&$body, &$bytes, $limit, $output): int {
                            $length = strlen($chunk);
                            if ($bytes + $length > $limit) return 0;
                            $bytes += $length;
                            if (is_resource($output)) {
                                return fwrite($output, $chunk) ?: 0;
                            }
                            $body .= $chunk;
                            return $length;
                        },
                    ];
                    if (defined('CURLOPT_PROTOCOLS_STR')) {
                        $options[CURLOPT_PROTOCOLS_STR] = 'https';
                    } else {
                        $options[CURLOPT_PROTOCOLS] = CURLPROTO_HTTPS;
                    }
                    curl_setopt_array($ch, $options);
                    if (curl_exec($ch) !== true) throw new RuntimeException('HTTPS download failed.');
                    return ['status' => (int)curl_getinfo($ch, CURLINFO_HTTP_CODE), 'body' => $body, 'location' => $location];
                } finally {
                    // Release the CurlHandle without PHP 8.5 deprecated curl_close().
                    unset($ch);
                }
            }
            $context = stream_context_create([
                'http' => [
                    'method' => 'GET', 'header' => implode("\r\n", $headers) . "\r\n",
                    'timeout' => 30, 'follow_location' => 0, 'max_redirects' => 0,
                    'ignore_errors' => true,
                ],
                'ssl' => ['verify_peer' => true, 'verify_peer_name' => true],
            ]);
            $stream = @fopen($url, 'rb', false, $context);
            if ($stream === false) throw new RuntimeException('HTTPS request failed.');
            try {
                $meta = stream_get_meta_data($stream);
                $status = 0;
                foreach ($meta['wrapper_data'] ?? [] as $line) {
                    if ($status === 0 && preg_match('~^HTTP/\d(?:\.\d)?\s+(\d{3})~i', (string)$line, $m)) {
                        $status = (int)$m[1];
                    }
                    if (str_starts_with(strtolower((string)$line), 'location:')) {
                        $location = trim(substr((string)$line, 9));
                    }
                }
                while (!feof($stream)) {
                    $chunk = fread($stream, min(65536, $limit + 1 - $bytes));
                    if (!is_string($chunk) || $chunk === '') {
                        if (!feof($stream)) throw new RuntimeException('Interrupted HTTPS stream.');
                        break;
                    }
                    $bytes += strlen($chunk);
                    if ($bytes > $limit) throw new RuntimeException('Oversized release response.');
                    if (is_resource($output)) {
                        if (fwrite($output, $chunk) !== strlen($chunk)) {
                            throw new RuntimeException('Interrupted private download.');
                        }
                    } else {
                        $body .= $chunk;
                    }
                }
                return ['status' => $status, 'body' => $body, 'location' => $location];
            } finally {
                fclose($stream);
            }
        } finally {
            if (is_resource($output)) fclose($output);
        }
    }
}
